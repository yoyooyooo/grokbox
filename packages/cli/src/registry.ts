export function leafKey(path: readonly string[]): string {
  return path.join(" ");
}

export function renderCommandReference(cliVersion: string): string {
  const lines: string[] = [
    "# grokbox command reference",
    "",
    `CLI version: ${cliVersion}`,
    "",
    `Top-level names: ${TOP_LEVEL_COMMANDS.join(", ")}.`,
    "There is no raw / api fallback. Unknown names are local usage errors.",
    "",
    "## Leaf commands",
    "",
  ];
  for (const leaf of LEAF_COMMANDS) {
    lines.push(`### \`${leafKey(leaf.path)}\``, "", "```text", leaf.usage, "```", "", leaf.summary, "");
    lines.push(`- target: ${leaf.arguments.find((arg) => arg.role)?.role ?? "none"}`);
    lines.push(`- options: ${leaf.options.map((option) => option.flags).join(", ") || "none"}`);
    lines.push(`- table: ${leaf.table ? "yes" : "no"}`);
    lines.push(`- timeout: ${leaf.timeout ? "yes" : "no"}`);
    lines.push(`- stdin: ${leaf.stdin}`);
    lines.push(`- destructive: ${leaf.destructive ? "yes" : "no"}`);
    lines.push(`- gateway: ${leaf.gateway ? "yes" : "no"}`);
    lines.push(`- streaming: ${leaf.streaming ? "yes" : "no"}`, "");
  }
  lines.push("## Copy-paste", "", "```bash", ...EXAMPLES, "```", "");
  lines.push("Do not pass `--token`, `--gateway-url`, `--host`, or `--port`.");
  lines.push("Reuse `--nonce` when retrying the same send.", "");
  return lines.join("\n");
}

